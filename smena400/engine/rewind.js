/**
 * Возврат к ключевому решению.
 *
 * Главная механика повторного прохождения в этом продукте — не «начать
 * сначала», а «вернуться к развилке и попробовать иначе». Разница
 * принципиальная: начиная сначала, человек переигрывает всё, включая то,
 * в чём был прав, и теряет ощущение, что проверяет именно одну гипотезу.
 *
 * Реализовано это не сохранением снимков состояния, а **повторным
 * исполнением записанного пути**. Движок детерминирован по построению:
 * одни и те же входы при одном и том же сценарии дают одно и то же
 * состояние. Поэтому достаточно прогнать журнал заново до нужного шага.
 *
 * Побочный эффект, ради которого стоило делать именно так: воспроизведение
 * — это ещё и непрерывная проверка детерминированности. Если бы движок хоть
 * где-то зависел от случайности, времени или внешнего сервиса, возврат
 * к развилке начал бы расходиться с оригиналом, и это было бы видно сразу.
 */
import { startSession, step } from './machine.js'

/**
 * Воспроизвести путь до указанного шага.
 *
 * `upToStep` — номер шага, ПЕРЕД которым нужно остановиться. Шаг 1 означает
 * «в самое начало, ничего не выполнять», шаг 3 — «выполнить первые два хода
 * и встать на третьем».
 *
 * Возвращает сессию в этой точке либо ошибку, если журнал не воспроизводится.
 * Молча подставлять «похожее» состояние нельзя: это означало бы показать
 * человеку развилку, на которой он не был.
 */
export function rewindTo(scenario, log, upToStep, { now = Date.now() } = {}) {
  const actions = (log ?? []).filter((l) => l.type === 'action')
  const target = Number(upToStep)

  // Допустимо и «на шаг после последнего»: это конец записанного пути,
  // и он нужен, чтобы воспроизвести путь целиком и сверить результат.
  if (!Number.isInteger(target) || target < 1 || target > actions.length + 1) {
    return { ok: false, error: `шаг ${upToStep} вне записанного пути` }
  }

  let session = startSession(scenario, { now })

  for (const entry of actions.slice(0, target - 1)) {
    /*
     * Время берётся из журнала: сколько человек думал тогда, столько же
     * «думает» и сейчас. Это важно для состояний с таймером — иначе шаг,
     * который в оригинале был бездействием, воспроизвёлся бы как обычный
     * выбор и увёл путь в другую ветку.
     */
    const at = session.stateEnteredAt + Math.max(0, entry.thinkMs ?? 0)

    const input = entry.timedOut
      ? { timeout: true }
      : Array.isArray(entry.order)
        ? { order: entry.order }
        : entry.said
          // Реплику прогоняем через тот же разбор, а не подставляем готовое
          // действие: если распознавание когда-нибудь разойдётся, возврат
          // к развилке сломается заметно, а не тихо.
          ? { said: entry.said }
          : { actionId: entry.actionId }

    const out = step(scenario, session, input, { now: at })
    if (!out.ok) {
      return { ok: false, error: `шаг ${entry.step} не воспроизводится: ${out.error}` }
    }
    if (out.result.actionId && entry.actionId && out.result.actionId !== entry.actionId) {
      return {
        ok: false,
        error: `шаг ${entry.step} воспроизвёлся иначе: было «${entry.actionId}», стало «${out.result.actionId}»`
      }
    }
    session = out.session
  }

  if (session.status !== 'active') {
    return { ok: false, error: 'путь завершился раньше указанного шага' }
  }

  // Часы сбрасываются: на развилке человек снова получает полное время.
  return { ok: true, session: { ...session, stateEnteredAt: now, startedAt: now } }
}

/**
 * Развилки, к которым имеет смысл возвращаться.
 *
 * Только те шаги, где выбор действительно был: если в состоянии оставалось
 * одно доступное действие, возвращаться туда незачем — иначе получится
 * не «попробовать иначе», а «нажать то же самое».
 */
export function rewindPoints(log) {
  return (log ?? [])
    .filter((l) => l.type === 'action' && (l.offered?.length ?? 0) > 1)
    .map((l) => ({
      step: l.step,
      label: l.actionLabel,
      situation: l.stateText,
      key: Boolean(l.key),
      alternatives: (l.offered?.length ?? 1) - 1
    }))
}
