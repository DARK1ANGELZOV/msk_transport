/**
 * Справочник показателей состояния.
 *
 * Универсального набора шкал для всех ситуаций не существует: показатели
 * определяет конкретный сценарий, а движок лишь исполняет объявленное.
 * Здесь описано, какие показатели вообще бывают и что каждый означает;
 * какие из них показывать — решает паспорт сценария полем `scales`.
 *
 * Пара «лояльность + безопасность» стоит по умолчанию, потому что она
 * независима по построению: в хорошей ситуации показатели регулярно
 * расходятся — успокоить пассажира можно ценой безопасности, а безопасность
 * можно удержать так, что человек выйдет из поезда с ненавистью
 * к перевозчику. Именно расхождение и есть то, чему продукт учит.
 * Если бы показатели всегда двигались вместе, хватило бы одного.
 */
