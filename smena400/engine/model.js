/**
 * Модель «Смены 400»: что вообще существует в игровом мире.
 *
 * Здесь намеренно очень мало сущностей. Две шкалы, пять компетенций,
 * пять типов взаимодействия — и всё. Каждая добавленная сюда сущность
 * размывает продуктовую петлю, а петля здесь важнее количества функций.
 */

// ---------------------------------------------------------------------------
// Шкалы
// ---------------------------------------------------------------------------

/**
 * Две шкалы, и они независимы.
 *
 * Это не «оценка хорошо/плохо», разложенная надвое. Это два разных среза
 * одной ситуации, и в хорошем сценарии они регулярно расходятся: успокоить
 * пассажира можно ценой безопасности, а безопасность можно удержать так,
 * что человек выйдет из поезда с ненавистью к перевозчику.
 *
 * Именно расхождение шкал — то, чему продукт учит. Если бы они всегда
 * двигались вместе, хватило бы одной.
 */
export const SCALES = [
  {
    id: 'loyalty',
    title: 'Лояльность пассажира',
    short: 'Лояльность',
    hint: 'Отношение пассажира к взаимодействию и качеству обслуживания'
  },
  {
    id: 'safety',
    title: 'Рейтинг безопасности',
    short: 'Безопасность',
    hint: 'Соответствие действий требованиям безопасного поведения'
  }
]

export const SCALE_IDS = SCALES.map((s) => s.id)

export const SCALE_MIN = 0
export const SCALE_MAX = 100

export const clamp = (v, lo = SCALE_MIN, hi = SCALE_MAX) =>
  Math.max(lo, Math.min(hi, Math.round(v)))

// ---------------------------------------------------------------------------
// Компетенции
// ---------------------------------------------------------------------------

/**
 * Компетенции — не шкалы интерфейса и не отдельные тесты.
 *
 * Они вычисляются из истории действий: каждое решение несёт вклад в одну-две
 * компетенции, и в разборе видно, какие из них проявились. Отдельного
 * «экзамена на приоритизацию» в продукте нет и не должно быть — приоритизация
 * проявляется тогда, когда на экране две проблемы и время на одну.
 */
export const COMPETENCIES = [
  { id: 'safety', title: 'Безопасность', hint: 'Удержание безопасного состояния ситуации' },
  { id: 'communication', title: 'Коммуникация', hint: 'Ясность, полнота и уместность сообщения' },
  { id: 'deescalation', title: 'Деэскалация', hint: 'Снижение напряжения вместо его наращивания' },
  { id: 'prioritization', title: 'Приоритизация', hint: 'Выбор главного, когда важного больше одного' },
  { id: 'decision', title: 'Принятие решений', hint: 'Своевременность и обоснованность выбора' }
]

export const COMPETENCY_IDS = COMPETENCIES.map((c) => c.id)

export const competencyTitle = (id) =>
  COMPETENCIES.find((c) => c.id === id)?.title ?? id

export const emptyCompetency = () =>
  Object.fromEntries(COMPETENCY_IDS.map((id) => [id, 0]))

// ---------------------------------------------------------------------------
// Взаимодействие
// ---------------------------------------------------------------------------

/**
 * Типы взаимодействия из базы продукта.
 *
 * `idle` (бездействие) стоит в одном ряду с остальными не случайно:
 * истечение таймера — это исход, а не отсутствие исхода. Движок обрабатывает
 * его тем же кодом, что и осознанный выбор, и записывает в историю так же.
 */
export const ACTION_KINDS = ['choice', 'say', 'sequence', 'escalate', 'idle']

/** Этапы поездки — контекст ситуации, а не украшение. */
export const TRIP_STAGES = ['посадка', 'отправление', 'движение', 'обслуживание', 'прибытие']

/** Классы обслуживания: подтверждены базой продукта (974-р). */
export const SERVICE_CLASSES = ['стандарт', 'комфорт', 'бизнес', 'первый']

/**
 * Уровни срочности. Влияют только на подачу: продукт не должен делать вид,
 * что «высокая срочность» сама по себе меняет нормативные требования.
 */
export const URGENCY = ['низкая', 'средняя', 'высокая', 'критическая']

