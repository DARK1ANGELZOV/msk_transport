/**
 * Финал описывается не числом, а состоянием, в которое пришла ситуация.
 *
 * Сознательно нет «оценки за прохождение» в процентах: продукт учит видеть
 * последствия, а не набирать баллы. Число здесь появилось бы ровно затем,
 * чтобы его оптимизировать вместо того, чтобы думать о пассажире.
 */
export const VERDICTS = {
  good: { id: 'good', title: 'Ситуация закрыта', tone: 'good' },
  mixed: { id: 'mixed', title: 'Ситуация закрыта с издержками', tone: 'warn' },
  bad: { id: 'bad', title: 'Ситуация вышла из-под контроля', tone: 'danger' }
}

export const verdictTitle = (id) => VERDICTS[id]?.title ?? 'Ситуация завершена'
